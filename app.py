# MAIN PREDICTION FUNCTION
# ==============================

def predict_whatif(season, traffic_reduction, construction_ban,
                   odd_even, crop_burning, month, hour, target_aqi):

    season_map = {
        "Winter": "winter",
        "Summer": "summer",
        "Monsoon": "monsoon",
        "Post Monsoon": "post_monsoon"
    }

    selected_season = season_map[season]
    sample = df[df["season"] == selected_season].iloc[0].copy()
    sample["month"] = month
    sample["hour"] = hour

    baseline, final_aqi, improvement = simulate(
        sample, traffic_reduction, construction_ban, odd_even, crop_burning
    )

    baseline_cat, baseline_color = get_aqi_category(baseline)
    final_cat, final_color = get_aqi_category(final_aqi)

    aqi_saved = baseline - final_aqi
    level_change = category_levels[baseline_cat] - category_levels[final_cat]

    required_reduction = calculate_required_reduction(
        sample, target_aqi, construction_ban, crop_burning
    )

    people_at_risk_before = get_health_impact(baseline)
    people_at_risk_after = get_health_impact(final_aqi)
    people_protected = people_at_risk_before - people_at_risk_after

    # ==============================
    # HTML SUMMARY
    # ==============================

    interventions_list = []
    if traffic_reduction > 0:
        interventions_list.append(f"Traffic Reduction: {traffic_reduction}%")
    if odd_even:
        interventions_list.append("Odd-Even Scheme: Active")
    if construction_ban:
        interventions_list.append("Construction Ban: Yes")
    if crop_burning:
        interventions_list.append("Crop Burning Effect: Included")

    interventions_str = "<br>".join(interventions_list) if interventions_list else "None"

    summary = f"""
    <h3>INTERVENTION SUMMARY</h3>
    <hr>
    <b>Season:</b> {season}<br>
    <b>Interventions:</b><br>{interventions_str}<br><br>

    <b>Baseline AQI:</b>
    <span style='color:{baseline_color}; font-weight:bold; font-size:18px'>
        {baseline:.0f} ({baseline_cat})
    </span><br>

    <b>Predicted AQI:</b>
    <span style='color:{final_color}; font-weight:bold; font-size:18px'>
        {final_aqi:.0f} ({final_cat})
    </span><br><br>

    <b>Improvement:</b> {improvement:.1f}%<br><br>

    <div style='font-size:22px; font-weight:bold; color:#2E86C1'>
        AQI POINTS SAVED: {aqi_saved:.0f}
    </div>

    <hr>
    <b>Category Improvement:</b><br>
    <span style='color:{baseline_color}; font-weight:bold'>{baseline_cat}</span>
    →
    <span style='color:{final_color}; font-weight:bold'>{final_cat}</span><br>
    <b>Level Shift:</b> {level_change} Category Levels Improved

    <hr>
    <h4>HEALTH IMPACT</h4>
    <b>People at Risk Before:</b>
    {people_at_risk_before:,}<br>
    <b>People Protected:</b>
    <span style='color:#00cc44; font-weight:bold; font-size:16px'>
        {people_protected:,}
    </span><br><br>

    <hr>
    <h4>TARGET GOAL ANALYSIS</h4>
    To reach AQI <b>{target_aqi}</b>,<br>
    Required Traffic Reduction ≈ <b>{required_reduction}%</b>
    """

    # ==============================
    # MATPLOTLIB PLOTS
    # ==============================

    fig, axes = plt.subplots(1, 2, figsize=(12, 5))

    axes[0].bar(
        ["Baseline", "After Intervention"],
        [baseline, final_aqi],
        color=[baseline_color, final_color],
        edgecolor='black',
        linewidth=0.5
    )
    axes[0].axhline(y=100, color='green', linestyle='--', alpha=0.5, label='Satisfactory')
    axes[0].axhline(y=200, color='orange', linestyle='--', alpha=0.5, label='Moderate')
    axes[0].axhline(y=300, color='red', linestyle='--', alpha=0.5, label='Poor')
    axes[0].set_ylim(0, 550)
    axes[0].set_title("Baseline vs Predicted AQI")
    axes[0].set_ylabel("AQI")
    axes[0].legend(fontsize=8)

    for bar, val in zip(axes[0].patches, [baseline, final_aqi]):
        axes[0].text(
            bar.get_x() + bar.get_width() / 2,
            bar.get_height() + 5,
            f'{val:.0f}',
            ha='center', va='bottom',
            fontsize=12, fontweight='bold'
        )

    reductions = list(range(0, 81, 10))
    predicted_aqis = []

    for r in reductions:
        _, adj, _ = simulate(sample, r, construction_ban, odd_even, crop_burning)
        predicted_aqis.append(adj)

    axes[1].plot(reductions, predicted_aqis,
                 marker='o', color='steelblue',
                 linewidth=2, markersize=6,
                 label='Predicted AQI')
    axes[1].axhline(y=100, color='green', linestyle='--', alpha=0.5, label='Satisfactory')
    axes[1].axhline(y=200, color='orange', linestyle='--', alpha=0.5, label='Moderate')
    axes[1].axhline(y=300, color='red', linestyle='--', alpha=0.5, label='Poor')
    axes[1].axvline(x=traffic_reduction, color='purple',
                    linestyle=':', alpha=0.7,
                    label=f'Selected ({traffic_reduction}%)')
    axes[1].set_xlabel("Traffic Reduction (%)")
    axes[1].set_ylabel("Predicted AQI")
    axes[1].set_title("AQI vs Traffic Reduction")
    axes[1].legend(fontsize=8)

    plt.tight_layout()

    # ==============================
    # PLOTLY GAUGE
    # ==============================

    gauge = go.Figure(go.Indicator(
        mode="gauge+number",
        value=final_aqi,
        title={'text': "Predicted AQI"},
        gauge={
            'axis': {'range': [0, 500]},
            'bar': {'color': final_color},
            'steps': [
                {'range': [0, 50],    'color': "#00e400"},
                {'range': [50, 100],  'color': "#92d050"},
                {'range': [100, 200], 'color': "#ffff00"},
                {'range': [200, 300], 'color': "#ff7e00"},
                {'range': [300, 400], 'color': "#ff0000"},
                {'range': [400, 500], 'color': "#7e0023"},
            ],
        }
    ))

    # ==============================
    # GENERATE PDF
    # ==============================

    pdf_path = generate_pdf(
        season, traffic_reduction, construction_ban,
        odd_even, crop_burning, month, hour, target_aqi,
        baseline, final_aqi, improvement,
        baseline_cat, final_cat, aqi_saved,
        level_change, required_reduction,
        people_at_risk_before, people_protected
    )

    return summary, fig, gauge, pdf_path


