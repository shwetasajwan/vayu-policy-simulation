# ==============================
# AQI CATEGORY + COLOR
# ==============================

def get_aqi_category(aqi):
    if aqi <= 50:
        return "Good", "#00e400"
    elif aqi <= 100:
        return "Satisfactory", "#92d050"
    elif aqi <= 200:
        return "Moderate", "#ffff00"
    elif aqi <= 300:
        return "Poor", "#ff7e00"
    elif aqi <= 400:
        return "Very Poor", "#ff0000"
    else:
        return "Severe", "#7e0023"


category_levels = {
    "Good": 1,
    "Satisfactory": 2,
    "Moderate": 3,
    "Poor": 4,
    "Very Poor": 5,
    "Severe": 6
}


# ==============================
# HEALTH IMPACT CALCULATOR
# ==============================

DELHI_POPULATION = 20_000_000

def get_health_impact(aqi):
    if aqi > 300:
        risk_percent = 100
    elif aqi > 200:
        risk_percent = 60
    elif aqi > 100:
        risk_percent = 30
    else:
        risk_percent = 10
    return int((risk_percent / 100) * DELHI_POPULATION)


# ==============================
# SIMULATION FUNCTION
# ==============================

def simulate(row, traffic_percent, construction, odd_even, crop_burning):
    row = row.copy()
    row["season_encoded"] = le_season.transform([row["season"]])[0]
    row["dow_encoded"] = le_dow.transform([row["day_of_week"]])[0]

    baseline_input = pd.DataFrame([row[features]])
    baseline_aqi = model.predict(baseline_input)[0]

    # Crop burning adds ~100 AQI points in Oct-Nov
    if crop_burning:
        baseline_aqi = min(baseline_aqi + 100, 500)

    # Odd-Even = effective 40% traffic reduction
    effective_traffic = traffic_percent
    if odd_even:
        effective_traffic = max(traffic_percent, 40)

    traffic_improvement = min((effective_traffic / 80) * 50, 50)

    if construction:
        total_improvement = traffic_improvement + 15 * (1 - traffic_improvement / 100)
        total_improvement = min(total_improvement, 60)
    else:
        total_improvement = traffic_improvement

    adjusted_aqi = baseline_aqi * (1 - total_improvement / 100)

    return round(baseline_aqi, 2), round(adjusted_aqi, 2), round(total_improvement, 2)


# ==============================
# TARGET AQI CALCULATOR
# ==============================

def calculate_required_reduction(row, target_aqi, construction, crop_burning):
    row = row.copy()
    row["season_encoded"] = le_season.transform([row["season"]])[0]
    row["dow_encoded"] = le_dow.transform([row["day_of_week"]])[0]

    baseline_input = pd.DataFrame([row[features]])
    baseline = model.predict(baseline_input)[0]

    if crop_burning:
        baseline = min(baseline + 100, 500)

    required_drop_percent = ((baseline - target_aqi) / baseline) * 100

    if required_drop_percent <= 0:
        return 0

    traffic_needed = (required_drop_percent / 50) * 80
    return round(max(0, min(traffic_needed, 80)), 1)


